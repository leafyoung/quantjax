"""Port of quantburn/src/black_scholes_merton.rs (itself a port of
torchquantlib core/asset_pricing/option/black_scholes_merton.py).

Closed-form scalar math in plain Python floats (f64). Also provides the
package-shared high-accuracy `erf` / `normal_cdf` (double precision: Taylor
series for |x| < 2.5, trapezoid-quadrature erfc tail for larger |x|), used by
the other option modules.
"""

import math

_SQRT_PI = math.sqrt(math.pi)


def erf(x: float) -> float:
    """Error function, double precision (~1e-15). Series for |x| < 2.5,
    quadrature erfc tail for larger |x|."""
    if abs(x) < 2.5:
        # erf(x) = 2/sqrt(pi) * sum_{n>=0} (-1)^n x^(2n+1) / (n! * (2n+1))
        x2 = x * x
        term = x
        total = x
        n = 0
        while n < 300:
            n += 1
            term *= -x2 / n
            add = term / (2 * n + 1)
            total += add
            if abs(add) < 1e-18 * (abs(total) + 1.0) or abs(term) < 1e-300:
                break
        return 2.0 / _SQRT_PI * total
    if x > 0.0:
        return 1.0 - _erfc_tail(x)
    return _erfc_tail(-x) - 1.0


def _erfc_tail(x: float) -> float:
    """erfc(x) for x >= 2.5 via the substitution
    erfc(x) = 2*exp(-x^2)/sqrt(pi) * int_0^inf exp(-2*x*s - s^2) ds,
    evaluated with a trapezoid rule (spectrally accurate for this
    super-exponentially decaying integrand; ~1e-16 relative)."""
    h = 0.01
    smax = 30.0 / x
    n = math.ceil(smax / h)
    total = 0.0
    for k in range(n + 1):
        s = k * h
        w = 0.5 if (k == 0 or k == n) else 1.0
        total += w * math.exp(-2.0 * x * s - s * s)
    return 2.0 * math.exp(-x * x) / _SQRT_PI * total * h


def normal_cdf(x: float) -> float:
    """Standard normal CDF."""
    return 0.5 * (1.0 + erf(x / math.sqrt(2.0)))


def _deterministic_option_value(
    option_type: str,
    spot: float,
    strike: float,
    expiry: float,
    rate: float,
    dividend: float,
) -> float:
    """Zero-volatility value: discounted max(forward - strike, 0) style payoff."""
    forward_spot = spot * math.exp((rate - dividend) * expiry)
    discount_factor = math.exp(-rate * expiry)
    if option_type == "call":
        return discount_factor * max(forward_spot - strike, 0.0)
    return discount_factor * max(strike - forward_spot, 0.0)


def black_scholes_merton(
    option_type: str,
    option_style: str,
    spot: float,
    strike: float,
    expiry: float,
    volatility: float,
    rate: float,
    dividend: float,
) -> float:
    """Price a Black-Scholes-Merton option.

    `option_style = "american"` uses the same lower-bounded approximation as
    the Python source: max(european price, intrinsic value).
    """
    if option_type not in ("call", "put"):
        raise ValueError("option_type must be either 'call' or 'put'.")
    if option_style not in ("european", "american"):
        raise ValueError("option_style must be either 'european' or 'american'.")

    if volatility <= 0.0:
        european_price = _deterministic_option_value(
            option_type, spot, strike, expiry, rate, dividend
        )
    else:
        sqrt_expiry = math.sqrt(expiry)
        d1 = (
            math.log(spot / strike)
            + (rate - dividend + 0.5 * volatility * volatility) * expiry
        ) / (volatility * sqrt_expiry)
        d2 = d1 - volatility * sqrt_expiry
        nd1 = normal_cdf(d1)
        nd2 = normal_cdf(d2)
        if option_type == "call":
            european_price = (
                spot * math.exp(-dividend * expiry) * nd1
                - strike * math.exp(-rate * expiry) * nd2
            )
        else:
            european_price = (
                strike * math.exp(-rate * expiry) * (1.0 - nd2)
                - spot * math.exp(-dividend * expiry) * (1.0 - nd1)
            )

    if option_style == "european":
        return european_price
    if option_type == "call":
        intrinsic_value = max(spot - strike, 0.0)
    else:
        intrinsic_value = max(strike - spot, 0.0)
    return max(european_price, intrinsic_value)


def _rel(a: float, b: float) -> float:
    return abs(a - b) / max(abs(b), 1e-300)


# --- tests (expected values from quantburn's black_scholes_merton.rs tests,
# generated by scripts/gen_black_scholes_merton.py, pure f64) ---


def test_european_call_put():
    assert abs(black_scholes_merton("call", "european", 100.0, 100.0, 1.0, 0.2, 0.05, 0.02) - 9.227005508154036) < 1e-9
    assert abs(black_scholes_merton("put", "european", 100.0, 100.0, 1.0, 0.2, 0.05, 0.02) - 6.330080627549918) < 1e-9


def test_american_style_is_max_of_european_and_intrinsic():
    # ITM put where intrinsic dominates.
    v = black_scholes_merton("put", "american", 80.0, 100.0, 1.0, 0.1, 0.05, 0.0)
    assert abs(v - 20.0) < 1e-9
    # OTM call: american == european (intrinsic = 0 < european).
    c = black_scholes_merton("call", "american", 90.0, 100.0, 1.0, 0.3, 0.02, 0.0)
    assert abs(c - 7.64638494703226) < 1e-9


def test_zero_volatility_deterministic():
    v = black_scholes_merton("call", "european", 100.0, 90.0, 2.0, 0.0, 0.03, 0.01)
    assert abs(v - 13.261059308093147) < 1e-9
    p = black_scholes_merton("put", "european", 100.0, 100.0, 2.0, 0.0, 0.03, 0.01)
    assert abs(p) < 1e-12


def test_normal_cdf_accuracy():
    # Reference: scipy.stats.norm.cdf.
    assert abs(normal_cdf(0.0) - 0.5) < 1e-14
    assert abs(normal_cdf(1.0) - 0.8413447460685429) < 1e-14
    assert abs(normal_cdf(-2.5) - 0.006209665325776132) < 1e-13
    assert abs(normal_cdf(6.0) - 0.9999999990134123) < 1e-12


def test_invalid_inputs_raise():
    import pytest

    with pytest.raises(ValueError):
        black_scholes_merton("straddle", "european", 100.0, 100.0, 1.0, 0.2, 0.05, 0.0)
    with pytest.raises(ValueError):
        black_scholes_merton("call", "bermudan", 100.0, 100.0, 1.0, 0.2, 0.05, 0.0)
