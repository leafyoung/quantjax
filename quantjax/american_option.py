"""Port of quantburn/src/american_option.rs (itself a port of torchquantlib
core/asset_pricing/option/american_option.py).

Thin wrapper around ``quantjax.option_utils.price_binomial_tree`` with
``option_style = "american"``; requires positive volatility, matching the
Python ``RuntimeError`` with a ``ValueError``.
"""


def american_option(
    option_type,
    spot,
    strike,
    expiry,
    volatility,
    rate,
    steps,
):
    """Price an American option with a CRR binomial tree."""
    if volatility <= 0.0:
        raise ValueError("volatility must be positive for american_option.")
    from quantjax.option_utils import price_binomial_tree

    return price_binomial_tree(
        option_type, "american", spot, strike, expiry, volatility, rate, steps, None
    )


def _rel(a, b):
    return abs(a - b) / max(abs(b), 1e-300)


# --- tests (expected values from quantburn's american_option.rs tests,
# generated by scripts/gen_american_option.py, pure f64) ---


def test_american_put():
    # put, S=100 K=100 T=1 vol=0.2 r=0.05, 50 steps
    assert abs(american_option("put", 100.0, 100.0, 1.0, 0.2, 0.05, 50) - 6.073727985724901) < 1e-9


def test_american_call():
    # call, S=100 K=100 T=1 vol=0.2 r=0.05, 50 steps
    assert (
        abs(american_option("call", 100.0, 100.0, 1.0, 0.2, 0.05, 50) - 10.410691540732644) < 1e-9
    )


def test_deep_itm_put_hits_intrinsic():
    # With few steps and deep ITM put, early exercise approximates intrinsic.
    v = american_option("put", 80.0, 100.0, 1.0, 0.2, 0.05, 10)
    assert abs(v - 20.0) < 1e-9


def test_zero_volatility_raises():
    import pytest

    with pytest.raises(ValueError, match="volatility must be positive"):
        american_option("put", 100.0, 100.0, 1.0, 0.0, 0.05, 10)
