"""Port of quantburn/src/bermudan_option.rs (itself a port of torchquantlib
core/asset_pricing/option/bermudan_option.py).

Thin wrapper around ``quantjax.option_utils.price_binomial_tree`` with
``option_style = "bermudan"``; ``exercise_dates`` are the step indices
(0 <= step < steps) at which early exercise is allowed.
"""


def bermudan_option(
    option_type,
    spot,
    strike,
    expiry,
    volatility,
    rate,
    steps,
    exercise_dates,
):
    """Price a Bermudan option with specified exercise steps."""
    if volatility <= 0.0:
        raise ValueError("volatility must be positive for bermudan_option.")
    from quantjax.option_utils import price_binomial_tree

    return price_binomial_tree(
        option_type,
        "bermudan",
        spot,
        strike,
        expiry,
        volatility,
        rate,
        steps,
        exercise_dates,
    )


def _rel(a, b):
    return abs(a - b) / max(abs(b), 1e-300)


# --- tests (expected values from quantburn's bermudan_option.rs tests,
# generated by scripts/gen_bermudan_option.py, pure f64) ---


def test_bermudan_put_quarterly_exercise():
    # put, S=100 K=100 T=1 vol=0.2 r=0.05, 50 steps, exercise at
    # steps 12, 24, 36.
    assert (
        abs(bermudan_option("put", 100.0, 100.0, 1.0, 0.2, 0.05, 50, [12, 24, 36]) - 5.93608249055333)
        < 1e-9
    )


def test_out_of_range_dates_are_filtered():
    # Steps >= steps or negative-equivalent entries are ignored, as in the
    # Python filter 0 <= step < steps.
    v_full = bermudan_option("put", 100.0, 100.0, 1.0, 0.2, 0.05, 50, [12, 24, 36])
    v_extra = bermudan_option("put", 100.0, 100.0, 1.0, 0.2, 0.05, 50, [12, 24, 36, 50, 99])
    assert abs(v_full - v_extra) < 1e-12
    # No valid dates -> European value.
    v_euro = bermudan_option("put", 100.0, 100.0, 1.0, 0.2, 0.05, 50, [])
    assert abs(v_euro - 5.533633990803824) < 1e-9


def test_bermudan_call():
    assert (
        abs(bermudan_option("call", 100.0, 100.0, 1.0, 0.2, 0.05, 50, [10, 20, 30, 40]) - 10.410691540732644)
        < 1e-9
    )


def test_zero_volatility_raises():
    import pytest

    with pytest.raises(ValueError, match="volatility must be positive"):
        bermudan_option("put", 100.0, 100.0, 1.0, 0.0, 0.05, 10, [5])
