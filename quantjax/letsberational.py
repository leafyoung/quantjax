"""Port of quantburn/src/letsberational.rs (itself a port of torchquantlib
core/asset_pricing/letsberational.py).

Black-Scholes helpers: normal CDF/PDF, Black-Scholes price, and implied
volatility via robust bisection on [1e-5, 5.0] with price tolerance 1e-8.

Note (faithful port of a source quirk): the bisection always prices a CALL
internally, even when ``is_call`` is false — ``is_call`` only affects the
no-arbitrage upper bound check. All math is scalar ``f64`` (plain Python
floats).
"""

import math

# Standard normal CDF: re-exported from quantjax.black_scholes_merton
# (high-accuracy erf, ~1e-15) instead of the former Abramowitz-Stegun 7.1.26
# approximation (~1.5e-7), mirroring the Python `torch.erf` accuracy.
from quantjax.black_scholes_merton import normal_cdf  # noqa: F401

__all__ = ["normal_cdf", "normal_pdf", "implied_volatility"]


def normal_pdf(x):
    """Standard normal probability density function (coefficient 0.3989 as in
    the Python source)."""
    return 0.3989 * math.exp(-0.5 * x * x)


def _black_scholes_price(volatility, spot, strike, expiry, rate, is_call):
    sqrt_expiry = math.sqrt(expiry)
    d1 = (math.log(spot / strike) + (rate + 0.5 * volatility * volatility) * expiry) / (
        volatility * sqrt_expiry
    )
    d2 = d1 - volatility * sqrt_expiry
    discount_factor = math.exp(-rate * expiry)

    if is_call:
        return spot * normal_cdf(d1) - strike * discount_factor * normal_cdf(d2)
    return strike * discount_factor * normal_cdf(-d2) - spot * normal_cdf(-d1)


def implied_volatility(option_price, spot, strike, expiry, rate, is_call):
    """Estimate implied volatility with a robust bisection search.

    Raises ``ValueError`` on invalid inputs (non-positive price/spot/strike/
    expiry, price outside no-arbitrage bounds, or non-convergence), mirroring
    the ``RuntimeError``s in the Python source.
    """
    if option_price <= 0.0:
        raise ValueError("option_price must be positive.")
    if spot <= 0.0 or strike <= 0.0 or expiry <= 0.0:
        raise ValueError("spot, strike, and expiry must be positive.")

    discount_factor = math.exp(-rate * expiry)
    max_price = spot if is_call else strike * discount_factor
    if option_price >= max_price:
        raise ValueError("option_price is outside no-arbitrage bounds.")

    lower = 1e-5
    upper = 5.0
    tolerance = 1e-8

    lower_price = _black_scholes_price(lower, spot, strike, expiry, rate, True)
    if option_price <= lower_price:
        return lower

    for _ in range(100):
        mid = 0.5 * (lower + upper)
        model_price = _black_scholes_price(mid, spot, strike, expiry, rate, True)
        price_diff = model_price - option_price

        if abs(price_diff) < tolerance:
            return mid

        if price_diff > 0.0:
            upper = mid
        else:
            lower = mid

    raise ValueError("implied_volatility failed to converge.")


def _rel(a, b):
    return abs(a - b) / max(abs(b), 1e-300)


# --- tests (expected values from quantburn's letsberational.rs tests,
# generated by scripts/gen_misc_pricers.py, pure float64).
# normal_cdf re-uses the high-accuracy quantjax.black_scholes_merton erf
# (~1e-15 vs math.erf), so the implied-vol bisection follows the same midpoint
# sequence as the pure-f64 Python reference and results agree to ~1e-12;
# tolerances are correspondingly tight. ---


def test_normal_cdf():
    actual = normal_cdf(0.3)
    expected = 0.6179114221889526
    # High-accuracy shared erf: agrees with math.erf to ~1e-15.
    assert abs(actual - expected) <= 1e-12, f"actual {actual} vs expected {expected}"


def test_normal_pdf():
    actual = normal_pdf(0.3)
    expected = 0.38134739550322355
    assert abs(actual - expected) <= 1e-8, f"actual {actual} vs expected {expected}"


def test_implied_volatility_call():
    iv = implied_volatility(10.0, 100.0, 100.0, 1.0, 0.05, True)
    expected = 0.18797164959634072
    assert abs(iv - expected) <= 1e-9 * max(abs(expected), 1.0), (
        f"actual {iv} vs expected {expected}"
    )
    # Round-trip: price at recovered vol reproduces the market price.
    price = _black_scholes_price(iv, 100.0, 100.0, 1.0, 0.05, True)
    assert abs(price - 10.0) <= 1e-8, f"price {price}"


def test_implied_volatility_put():
    # Ported quirk: the bisection prices a call internally even for puts,
    # so this matches the Python reference value exactly.
    iv = implied_volatility(8.0, 100.0, 95.0, 0.5, 0.03, False)
    expected = 0.14666327622914455
    assert abs(iv - expected) <= 1e-9 * max(abs(expected), 1.0), (
        f"actual {iv} vs expected {expected}"
    )


def test_implied_volatility_bounds_error():
    import pytest

    with pytest.raises(ValueError):
        implied_volatility(0.0, 100.0, 100.0, 1.0, 0.05, True)
    with pytest.raises(ValueError):
        implied_volatility(200.0, 100.0, 100.0, 1.0, 0.05, True)
