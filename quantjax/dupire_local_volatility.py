"""Port of quantburn/src/dupire_local_volatility.rs (originally
torchquantlib/models/local_volatility/dupire_local_volatility.py — Dupire
local volatility model).

Euler logspot simulation where the local volatility surface `sigma(S, t)` is
supplied as a function. `simulate` performs `steps` Euler steps updating
`spot *= exp(rate*dt + sigma(spot, t)*sqrt(dt)*z)` with `t` evaluated at
`(step + 1) * dt`. A negative value from the surface raises ValueError.
Normals come from `quantjax.rng.Xorshift64Star` with an explicit `seed`
(module RNG seed in the Python source: 2009).
"""

import math
from typing import Callable, List

from quantjax.rng import Xorshift64Star


def simulate(
    local_vol_func: Callable[[float, float], float],
    s0: float,
    t: float,
    n: int,
    steps: int,
    rate: float,
    seed: int,
) -> List[float]:
    """Python `DupireLocalVol.simulate`: Euler steps over `n` paths."""
    steps = max(steps, 1)
    dt = t / steps
    sqrt_dt = math.sqrt(dt)
    spot = [s0] * n
    rng = Xorshift64Star(seed)
    for step in range(steps):
        time = (step + 1) * dt
        diffusion = []
        for s in spot:
            sigma = local_vol_func(s, time)
            if sigma < 0.0:
                raise ValueError("Negative volatility encountered")
            diffusion.append(sigma * sqrt_dt)
        for i in range(n):
            z = rng.next_std_normal()
            spot[i] *= math.exp(rate * dt + diffusion[i] * z)
    return spot


# ---------------------------------------------------------------------------
# Embedded parity tests (expected literals from
# quantburn/src/dupire_local_volatility.rs, generated by
# scripts/gen_dupire_local_volatility.py, tol 1e-12 relative)
# ---------------------------------------------------------------------------


def _rel(a: float, b: float) -> float:
    return abs(a - b) / max(abs(b), 1e-300)


def test_simulate_constant_surface_matches_reference():
    # Constant surface degenerates to geometric Brownian motion, seed 2009.
    out = simulate(lambda _s, _t: 0.2, 100.0, 1.0, 6, 32, 0.05, 2009)
    expected = [
        92.02458413250487,
        87.40917483785537,
        95.42764799048972,
        93.92498775669627,
        125.67360115565047,
        117.31017140023587,
    ]
    for got, want in zip(out, expected):
        assert _rel(got, want) < 1e-12, f"got={got} want={want}"


def test_simulate_state_dependent_surface_matches_reference():
    # Surface depending on spot and time is honoured (deterministic
    # spot-independent check embedded in the gen script too).
    def surface(s: float, t: float) -> float:
        return 0.1 + 0.2 * min(s / 100.0, 2.0) * (1.0 / (1.0 + t))

    out = simulate(surface, 100.0, 0.5, 4, 16, 0.02, 2009)
    expected = [
        96.02933173574249,
        96.63160341139788,
        93.29985284075049,
        142.54048922865078,
    ]
    for got, want in zip(out, expected):
        assert _rel(got, want) < 1e-12, f"got={got} want={want}"


def test_negative_volatility_raises():
    import pytest

    with pytest.raises(ValueError, match="Negative volatility encountered"):
        simulate(lambda _s, _t: -0.1, 100.0, 1.0, 2, 4, 0.0, 2009)
